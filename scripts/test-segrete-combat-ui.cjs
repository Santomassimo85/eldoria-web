const assert = require('node:assert/strict');
const esbuild = require('esbuild');
const Module = require('node:module');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const file = require('node:path').resolve('src/pages/SegreteCombatUI.jsx');
const code = esbuild.buildSync({ entryPoints: [file], bundle: true, platform: 'node', format: 'cjs', jsx: 'automatic', external: ['react', 'react/jsx-runtime'], write: false }).outputFiles[0].text;
const mod = new Module(file, module);
mod.paths = module.paths;
mod._compile(code, file);
const { FoeCard, FloorGains, SpoilsBox } = mod.exports;
const html = (Component, props) => renderToStaticMarkup(React.createElement(Component, props));
const foe = { name: 'Mimic', frontImg: '/front.png', img: '/archived.png', hp: 12, maxHp: 30, ac: 14, fx: {}, role: 'boss', level: 3 };
const card = html(FoeCard, { f: foe, known: true, kills: 2, round: 1 });
assert.match(card, /src="\/front.png"/);
assert.doesNotMatch(card, /archived.png|class="mirror"/);
assert.match(card, /12 \/ 30/);
const unknown = html(FoeCard, { f: foe, known: false, round: 1 });
assert.match(unknown, /\?\?\?\?/);
assert.doesNotMatch(unknown, /12 \/ 30/);
const run = { floor: 1, floors: 3, heroes: [{ uid: 'one' }], gains: { one: [{ fl: 1, c: 12 }, { fl: 2, c: 99 }] } };
const gains = html(FloorGains, { run, uid: 'one' });
assert.match(gains, /12/);
assert.doesNotMatch(gains, /99/);
assert.match(html(SpoilsBox, { run: { ...run, heroes: [{ uid: 'one', helper: true }] }, uid: 'one' }), /come aiuto/);
console.log('Segrete combat UI: frontal portrait, known/unknown stats, floor rewards and helper rewards passed.');
