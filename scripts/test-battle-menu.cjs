const assert = require('node:assert/strict');
const fs = require('node:fs');
const Module = require('node:module');
const { buildSync } = require('esbuild');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const app = fs.readFileSync('src/App.jsx', 'utf8');
const groups = app.slice(app.indexOf('const NESSO_GROUPS ='), app.indexOf('const NESSO_GROUP_OF ='));
const config = new Module(__filename, module);
config._compile(`${groups}\nmodule.exports = NESSO_GROUPS;`, __filename);
assert.deepEqual(config.exports.battaglia.links.map(l => l.to), ['/sala-della-gloria', '/world-boss-fight']);
assert.match(app, /key: "battaglia", g: "ᚦ", label: "Battaglia"/);
const sala = fs.readFileSync('src/pages/SalaGloria.jsx', 'utf8');
for (const route of ['/arena', '/segrete', '/torre-di-vethrik']) assert.ok(sala.includes(`to: "${route}"`));
const segrete = fs.readFileSync('src/pages/Segrete.jsx', 'utf8');
const towerTabs = segrete.slice(segrete.indexOf('const TORRE_TABS'), segrete.indexOf('const readTab'));
assert.match(towerTabs, /key: "manuale"/);
assert.doesNotMatch(towerTabs, /key: "bottega"/);
assert.match(segrete.slice(segrete.indexOf('const SEGRETE_TABS'), segrete.indexOf('const TORRE_TABS')), /key: "bottega"/);
assert.match(segrete, /isTowerPage \? <SegreteTowerManual \/> : <SegreteManual \/>/);
const code = buildSync({ entryPoints: ['src/pages/SegreteTowerManual.jsx'], bundle: true, format: 'cjs', platform: 'node', jsx: 'automatic', external: ['react', 'react/jsx-runtime'], write: false }).outputFiles[0].text;
const component = new Module(__filename, module); component.paths = module.paths; component._compile(code, __filename);
const html = renderToStaticMarkup(React.createElement(component.exports.default));
assert.equal((html.match(/<li>/g) || []).length, 6);
for (const text of ['Manuale della Torre', '4 eroi', '3 ingressi', '100 piani', 'ogni 5 piani', 'anche se è più basso', '23:00, ora italiana', 'Premi &amp; Reliquie']) assert.ok(html.includes(text), text);
const words = html.replace(/<[^>]+>/g, ' ').trim().split(/\s+/).length;
assert.ok(words < 180, `${words} parole`);
console.log(`OK: menu condiviso desktop/mobile, tre ingressi nella Sala e manuale Torre di sei punti (${words} parole).`);
