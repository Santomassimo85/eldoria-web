const assert = require('node:assert/strict');
const E = require('../functions/segreteBundle.js');
const original = { storyCoins: 10, storyBag: { pozione: 3, tonico: 2, future_hidden: 4 }, storyChars: { fighter: { weaponItem: 'spada_lunga_1' } }, storyShopDay: { day: 'today', n: { pozione: 3 } } };
const sale = E.sellBagItem(original, 'pozione', 2);
assert.equal(sale.unitPrice, 8);
assert.equal(sale.earned, 16);
assert.equal(sale.patch.storyCoins, 26);
assert.deepEqual(sale.patch.storyBag, { pozione: 1, tonico: 2, future_hidden: 4 });
assert.equal(original.storyBag.pozione, 3, 'Lo snapshot letto non viene modificato');
assert.throws(() => E.sellBagItem(original, 'spada_lunga_1'), /zaino/);
assert.throws(() => E.sellBagItem(original, '__proto__'), /sconosciuto/);
assert.throws(() => E.sellBagItem(original, 'constructor'), /sconosciuto/);
for (const qty of [0, -1, 1.5, Infinity, 'bad', 1000]) assert.throws(() => E.sellBagItem(original, 'pozione', qty));
assert.throws(() => E.sellBagItem(original, 'pozione', 4), /copie/);
const depleted = E.sellBagItem({ ...original, ...sale.patch }, 'pozione');
assert.equal(depleted.patch.storyBag.pozione, undefined);
assert.throws(() => E.sellBagItem(depleted.patch, 'pozione'), /copie/);
assert.equal(original.storyShopDay.n.pozione, 3, 'Vendere non riapre i limiti di acquisto');
assert.equal(E.sellBagItem({ storyBag: { tonico: 1 } }, 'tonico').earned, 13);
assert.equal(E.sellBagItem({ storyBag: { spada_lunga_1: 1 } }, 'spada_lunga_1').earned, 400);
assert.equal(E.sellBagItem({ storyBag: { spada_lunga_2: 1 } }, 'spada_lunga_2').earned, 300, 'Solo bottino: valore di rarità / 3');
E.registerCustomItems([{ id: 'x_sale_test', name: 'Test', kind: 'heal', rarity: 'rare', price: 0, tradeValue: 150, dice: '1d4' }]);
assert.equal(E.sellBagItem({ storyBag: { x_sale_test: 1 } }, 'x_sale_test').earned, 50);
E.registerCustomItems([{ id: 'x_sale_test', name: 'Test', kind: 'heal', rarity: 'rare', price: 30, tradeValue: 900, dice: '1d4' }]);
assert.equal(E.sellBagItem({ storyBag: { x_sale_test: 1 } }, 'x_sale_test').earned, 10, 'Il prezzo reale precede il valore di rarità');
console.log('OK: vendita a 1/3, arrotondamenti, quantità, zaino vuoto/equipaggiati, copie esaurite, oggetti sconosciuti, dati preservati e valori custom server.');
